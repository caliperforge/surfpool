/**
 * Regenerates the TypeScript bindings for the surfnet_* cheatcode wire types
 * from the Rust source of truth (crates/types, `ts-bindings` feature).
 *
 * Output goes to surfpool-sdk/kit/generated/ and is committed; CI regenerates
 * and fails on any diff, so the bindings can never drift from the Rust types.
 */
const { execFileSync } = require("node:child_process");
const fs = require("node:fs");
const path = require("node:path");

const repoRoot = path.resolve(__dirname, "..", "..", "..");
const packageDir = path.resolve(__dirname, "..");
const generatedDir = path.resolve(
  __dirname,
  "..",
  "surfpool-sdk",
  "kit",
  "generated",
);

// ts-rs emits unindented single-line type bodies, so the committed bindings are
// formatted here rather than left for a follow-up pass: the freshness job in
// .github/workflows/sdk_node.yml regenerates this directory and fails on any
// diff, so anything that formats the files *after* generation is reverted by the
// next run. Formatting has to happen inside the generator or not at all.
//
// The formatter runs through `npx <exact version>` instead of `require`: that job
// checks out the repo and runs this script with no `setup-node` and no `npm ci`,
// so there is no node_modules to resolve against and a bare require would throw
// MODULE_NOT_FOUND there while working fine locally. `npx` uses the local
// devDependency when it satisfies the spec and fetches it otherwise, so both
// environments format with the same bytes. The version comes from package.json
// so there is one place to bump it, and it is pinned exactly because a range
// would let two machines produce different output and turn the gate red.
const prettierVersion =
  JSON.parse(fs.readFileSync(path.join(packageDir, "package.json"), "utf8"))
    .devDependencies?.prettier ?? null;

function formatFiles(filePaths) {
  if (!prettierVersion) {
    throw new Error(
      "devDependencies.prettier is missing from crates/sdk-node/package.json; " +
        "the generated bindings cannot be formatted deterministically without a pinned version.",
    );
  }
  if (!/^\d+\.\d+\.\d+$/.test(prettierVersion)) {
    throw new Error(
      `devDependencies.prettier must be an exact version, got "${prettierVersion}"; ` +
        "a range lets different machines format the bindings differently and breaks the freshness gate.",
    );
  }
  execFileSync(
    process.platform === "win32" ? "npx.cmd" : "npx",
    [
      "--yes",
      `prettier@${prettierVersion}`,
      // Pinned flags, not preference: config discovery walks up past the repo
      // root, so without these the output would depend on files outside the
      // checkout and stop being reproducible in CI.
      "--no-config",
      "--no-editorconfig",
      "--log-level",
      "warn",
      "--write",
      ...filePaths,
    ],
    { cwd: packageDir, stdio: "inherit" },
  );
}

const HEADER = `// @generated by ts-rs from the Rust types in crates/types.\n// Do not edit; run \`npm run generate:kit-types\` in crates/sdk-node instead.\n`;

fs.rmSync(generatedDir, { recursive: true, force: true });

// No test-name filter: this must run the whole surfpool-types suite so the
// mirror serialization-equivalence and wire-key guard tests in ts_bindings.rs
// gate every regeneration, not just emit files.
execFileSync("cargo", ["test", "-p", "surfpool-types", "--features", "ts-bindings"], {
  cwd: repoRoot,
  env: {
    ...process.env,
    TS_RS_EXPORT_DIR: generatedDir,
    // The package compiles this directory to both CJS and ESM; Node ESM
    // requires explicit extensions on relative imports.
    TS_RS_IMPORT_EXTENSION: "js",
  },
  stdio: "inherit",
});

const files = fs
  .readdirSync(generatedDir)
  .filter((name) => name.endsWith(".ts"))
  .sort();

for (const name of files) {
  const filePath = path.join(generatedDir, name);
  const content = fs.readFileSync(filePath, "utf8");
  fs.writeFileSync(filePath, HEADER + content);
}

const barrel = files
  .map((name) => {
    const module = `./${name.replace(/\.ts$/, "")}.js`;
    // methods.ts exports a runtime const; everything else is type-only.
    return name === "methods.ts"
      ? `export * from "${module}";`
      : `export type * from "${module}";`;
  })
  .join("\n");
fs.writeFileSync(path.join(generatedDir, "index.ts"), `${HEADER}${barrel}\n`);

// Every file this script emits, index.ts included: a generator that formats part
// of its output leaves the rest to drift.
formatFiles(
  [...files, "index.ts"].map((name) => path.join(generatedDir, name)),
);

console.log(`Generated ${files.length} binding files in ${generatedDir}`);
